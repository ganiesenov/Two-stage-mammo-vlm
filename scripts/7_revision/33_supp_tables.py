def main():
    block = "\n".join([BEGIN, s3(), s4(), s5(), END])
    tex = open(SUPP, encoding="utf-8").read()
    if BEGIN in tex:
        a, b = tex.index(BEGIN), tex.index(END) + len(END)
        tex = tex[:a] + block + tex[b:]
    else:
        tex = tex.replace("\\end{document}", block + "\n\n\\end{document}")
    open(SUPP, "w", encoding="utf-8").write(tex)
    print(f"S3–S5 записаны в {SUPP}")


if __name__ == "__main__":
    main()
